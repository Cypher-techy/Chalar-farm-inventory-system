import { NextRequest, NextResponse } from 'next/server';
import { sql } from 'drizzle-orm';
import { getDb } from '@/db';
import { requireAuth, jsonError } from '@/lib/guards';
import { hasPermission, recordAuditLog } from '@/lib/auth';
import { buildPdf } from '@/lib/pdf';

export const dynamic = 'force-dynamic';

const kes = (v: string | number | null) =>
  `KES ${Number(v ?? 0).toLocaleString('en-KE', { minimumFractionDigits: 2, maximumFractionDigits: 2 })}`;

/**
 * Payslip PDF. Access: the employee concerned, or a holder of payroll.view /
 * hr.sensitive. Every download is audited.
 */
export async function GET(req: NextRequest, ctx: { params: Promise<{ number: string }> }) {
  try {
    const user = await requireAuth(req);
    const { number } = await ctx.params;
    const db = await getDb();

    const rows = (await db.execute(sql`
      SELECT ps.payslip_number, pr.run_code, pr.period_month, pr.pay_date, pr.statutory_version_code,
             pr.status AS run_status, e.employee_code, e.full_name, e.job_title, e.national_id_number,
             e.kra_pin, e.nssf_number, e.shif_number, e.bank_name, e.bank_account_number,
             e.pay_frequency, d.name AS department,
             ps.basic_pay_kes, ps.overtime_pay_kes, ps.allowances_kes, ps.gross_pay_kes,
             ps.nssf_employee_kes, ps.nssf_employer_kes, ps.shif_kes,
             ps.housing_levy_employee_kes, ps.housing_levy_employer_kes,
             ps.taxable_pay_kes, ps.paye_before_relief_kes, ps.personal_relief_kes, ps.paye_tax_kes,
             ps.other_deductions_kes, ps.net_pay_kes, ps.payment_status
      FROM payslip_records ps
      JOIN payroll_runs pr ON pr.id = ps.payroll_run_id
      JOIN employee_profiles e ON e.id = ps.employee_id
      JOIN departments d ON d.id = e.department_id
      WHERE ps.payslip_number = ${number}
      LIMIT 1;
    `)) as unknown as { rows: Array<Record<string, string>> };

    const p = rows.rows[0];
    if (!p) return jsonError(404, 'Payslip not found.');

    const privileged = hasPermission(user, 'payroll.view') || hasPermission(user, 'hr.sensitive');
    const isOwner = await isPayslipOwner(user.id, String(p.employee_code));
    if (!privileged && !isOwner) {
      return jsonError(403, 'You may only download your own payslip.');
    }

    const pdf = buildPdf({
      title: 'Payslip',
      subtitle: `Payslip ${p.payslip_number} · Payroll run ${p.run_code} (${p.run_status}) · Statutory rules ${p.statutory_version_code}`,
      sections: [
        {
          heading: 'Employee',
          lines: [
            `Name: ${p.full_name}`,
            `Employee code: ${p.employee_code}`,
            `Department: ${p.department}`,
            `Job title: ${p.job_title}`,
            `Pay frequency: ${p.pay_frequency}`,
            `Period: ${p.period_month}`,
            `Pay date: ${p.pay_date}`,
            `Bank: ${p.bank_name} — account ${privileged || isOwner ? p.bank_account_number : '****'}`,
          ],
        },
        {
          heading: 'Earnings',
          lines: [
            `Basic pay: ${kes(p.basic_pay_kes)}`,
            `Overtime pay: ${kes(p.overtime_pay_kes)}`,
            `Allowances: ${kes(p.allowances_kes)}`,
            `Gross pay: ${kes(p.gross_pay_kes)}`,
          ],
        },
        {
          heading: 'Statutory deductions (Kenya)',
          lines: [
            `NSSF (employee 6%, Tier I/II capped): ${kes(p.nssf_employee_kes)}`,
            `NSSF (employer contribution): ${kes(p.nssf_employer_kes)}`,
            `SHIF (2.75% of gross, min KES 300): ${kes(p.shif_kes)}`,
            `Affordable Housing Levy (employee 1.5%): ${kes(p.housing_levy_employee_kes)}`,
            `Affordable Housing Levy (employer 1.5%): ${kes(p.housing_levy_employer_kes)}`,
            `Taxable pay: ${kes(p.taxable_pay_kes)}`,
            `PAYE before personal relief: ${kes(p.paye_before_relief_kes)}`,
            `Personal relief: ${kes(p.personal_relief_kes)}`,
            `PAYE payable: ${kes(p.paye_tax_kes)}`,
            `Other deductions: ${kes(p.other_deductions_kes)}`,
          ],
        },
        {
          heading: 'Net pay',
          lines: [
            `Net pay: ${kes(p.net_pay_kes)}`,
            `Payment status: ${p.payment_status}`,
          ],
        },
      ],
      footerNote:
        'Generated by the Chalar Farms ERP from payroll records. Statutory rates follow the configured date-effective rule version — verify against KRA/NSSF/SHA guidance for filing. ' +
        (privileged && !isOwner ? `Viewed by ${user.fullName} (${user.email}) under payroll/HR permission.` : ''),
    });

    await recordAuditLog({
      actor: user,
      action: 'PAYSLIP_PDF_DOWNLOADED',
      module: 'PAYROLL',
      entityType: 'PAYSLIP',
      entityId: p.payslip_number,
      summary: `${privileged && !isOwner ? 'Administrator' : 'Employee'} downloaded payslip PDF for ${p.employee_code} (${p.period_month})`,
      ipAddress: req.headers.get('x-forwarded-for') ?? 'unknown',
    });

    return new NextResponse(Buffer.from(pdf), {
      status: 200,
      headers: {
        'Content-Type': 'application/pdf',
        'Content-Disposition': `attachment; filename="${p.payslip_number}.pdf"`,
        'Cache-Control': 'no-store',
      },
    });
  } catch (e) {
    const err = e as { status?: number; message?: string };
    if (err.status) return jsonError(err.status, err.message ?? 'Error');
    console.error('payslip pdf', e);
    return jsonError(500, 'Failed to generate payslip.');
  }
}

async function isPayslipOwner(userId: number, employeeCode: string): Promise<boolean> {
  const db = await getDb();
  const res = (await db.execute(sql`
    SELECT 1 AS ok FROM employee_profiles
    WHERE user_id = ${userId} AND employee_code = ${employeeCode} LIMIT 1;
  `)) as unknown as { rows: unknown[] };
  return res.rows.length > 0;
}
